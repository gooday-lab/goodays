/* ---------- Top Picks rendering ---------- */
function renderBestPicks() {
  const grid = document.getElementById('bestPicks');
  if (!grid || !Array.isArray(window.GOODAYS_PICKS)) return;
  const picks = window.GOODAYS_PICKS.slice(0, 3);
  grid.innerHTML = picks.map((pick, index) => {
    const badge = (pick.badge && (pick.badge[currentLang] || pick.badge.en)) || '';
    const verdict = (pick.verdict && (pick.verdict[currentLang] || pick.verdict.en)) || '';
    const pros = (pick.pros && (pick.pros[currentLang] || pick.pros.en)) || [];
    const url = window.goodaysBuildAffiliateUrl
      ? window.goodaysBuildAffiliateUrl(pick.shopeeUrl, `picks-${pick.id}`)
      : (pick.shopeeUrl || '');
    const ctaHref = url ? ` href="${escapeHtml(url)}" target="_blank" rel="nofollow sponsored noopener"` : ' href="#"';
    const prosLabel = translations[currentLang].pickProsLabel;
    return `<article class="pick-card ${index === 0 ? 'is-featured' : ''}">
      ${badge ? `<span class="pick-badge">${escapeHtml(badge)}</span>` : ''}
      <span class="pick-rank">0${index + 1}</span>
      <h3 class="pick-name">${escapeHtml(pick.name)}</h3>
      <div class="pick-meta">${renderStars(pick.rating)} <span>${escapeHtml(String(pick.rating || '—'))} / 5</span><span class="pick-price">${escapeHtml(pick.price || '')}</span></div>
      <p class="pick-verdict">${escapeHtml(verdict)}</p>
      <p class="pick-pros-label">${prosLabel}</p>
      <ul class="pick-pros">${pros.map((item) => `<li>${escapeHtml(item)}</li>`).join('')}</ul>
      <div class="pick-cta-row">
        <a class="button button-shopee affiliate-link" data-aff="pick-${escapeHtml(pick.id)}" data-product="${escapeHtml(pick.name)}"${ctaHref}>${translations[currentLang].checkPriceShopee}</a>
        <a class="text-link pick-review-link" href="${escapeHtml(pick.reviewUrl || 'reviews.html')}">${translations[currentLang].pickReviewLink}</a>
      </div>
    </article>`;
  }).join('');
}

/* ---------- Affiliate click tracking ---------- */
document.addEventListener('click', (event) => {
  const link = event.target.closest('a[data-aff]');
  if (!link) return;
  const name = link.dataset.product || link.textContent.trim().slice(0, 40);
  if (window.goodaysTrackAffiliateClick) window.goodaysTrackAffiliateClick(name, link.dataset.aff);
});

/* ---------- Announcement rotator ---------- */
(function announcementRotator() {
  const el = document.querySelector('.announcement-rotator');
  if (!el) return;
  let index = 0;
  setInterval(() => {
    index = (index + 1) % 3;
    el.classList.add('is-fading');
    setTimeout(() => {
      el.textContent = translations[currentLang][`rotator${index + 1}`] || el.textContent;
      el.classList.remove('is-fading');
    }, 350);
  }, 5200);
})();

/* ---------- Scroll reveal ---------- */
(function scrollReveal() {
  const items = document.querySelectorAll('.reveal');
  if (!items.length) return;
  if (!('IntersectionObserver' in window)) { items.forEach((item) => item.classList.add('is-visible')); return; }
  const observer = new IntersectionObserver((entries) => {
    entries.forEach((entry) => {
      if (entry.isIntersecting) { entry.target.classList.add('is-visible'); observer.unobserve(entry.target); }
    });
  }, { threshold: 0.15 });
  items.forEach((item) => observer.observe(item));
})();

/* ---------- Sticky CTA ---------- */
(function stickyCta() {
  const bar = document.getElementById('stickyCta');
  if (!bar) return;
  let shown = false;
  const toggle = () => {
    const shouldShow = window.scrollY > 650;
    if (shouldShow === shown) return;
    shown = shouldShow;
    if (shown) { bar.hidden = false; bar.classList.add('is-visible'); }
    else { bar.hidden = true; bar.classList.remove('is-visible'); }
  };
  window.addEventListener('scroll', toggle, { passive: true });
  toggle();
})();

